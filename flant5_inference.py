#!/usr/bin/env python

import torch
from transformers import T5Tokenizer, T5ForConditionalGeneration
import pandas as pd
import numpy as np
import os
import glob
import shutil
from collections import defaultdict
import unicodedata
import re

# Config
model_path = "/finetuned_models/flan_t5_unique_spans_w_context"
input_directory = "/Data/input"
processed_directory = "/Data/processed"
output_csv = "/results/predictions_retest.csv"

# Tokenizer
tokenizer = T5Tokenizer.from_pretrained(model_path)

# Load model
model = T5ForConditionalGeneration.from_pretrained(model_path)
model.eval()

# Use GPU if available
device = "cuda" if torch.cuda.is_available() else "cpu"
model.to(device)

print(f"Model loaded on {device}")

# Preprocess text
def clean_text(text: str) -> str:
    
    if not isinstance(text, str) or not text.strip():
        return ""

    text = text.upper()
    
    # Handle phrases after family history
    family_history_patterns = [
        "FAMILY HISTORY:",
        "FAMILY HISTORY :",
        "FAMILY HISTORY",
        "FAMILY HISTORY "
    ]

    for pattern in family_history_patterns:
        idx = text.find(pattern)
        if idx != -1:
            text = text[:idx]
            break

    # Normalize unicode
    text = unicodedata.normalize("NFKC", text)

    # Replace broken characters
    text = text.replace("�", " ")
    text = text.replace("UNABLE TO DISPLAY)", "UNABLE TO DISPLAY")


    # Remove HTML/XML artifacts
    text = re.sub(r"<[^>]+>", " ", text)
    text = re.sub(r"&lt;|&gt;|&amp;", " ", text)

    # Remove RTF
    text = re.sub(r"\{\\.*?\}", " ", text)
    text = re.sub(r"={2,}", " ", text)

    # Remove boilerplate EHR output
    EHR_PATTERNS = [
        r"(?i)HERE ARE SOME EXAMPLES",
        r"(?i)COMMON SIDE EFFECTS MAY INCLUDE",
        r"(?i)DOCUMENT CREATED BY.*",
        r"(?i)THIS NOTE WAS GENERATED BY.*",
        r"(?i)UNABLE TO DISPLAY.*",
        r"(?i)PLEASE DO NOT REPLY.*",
        r"(?i)TELL YOUR DOCTOR",
        r"(?i)PLEASE CALL",
        r"(?i)TRY THE FOLLOWING",
    ]

    for pat in EHR_PATTERNS:
        text = re.sub(pat, " ", text)

    # Normalize repeated punctuation
    text = re.sub(r"([!?.,])\1+", r"\1", text)

    # Normalize whitespace
    text = re.sub(r"\s+", " ", text).strip()

    return text

# Normalize prediction label
def normalize_label(x):
    x = x.lower()
    if "no social reference" in x:
        return "no social reference"
    if "social support" in x:
        return "social support"
    if "social isolation" in x:
        return "social isolation"
    return "unknown"

# Predict chunks
def predict_chunk(chunk_text):
    prompt = (
        f"Classify the text into exactly one category: "
        f"['social isolation', 'no social reference', or 'social support'].\n"
        f"Text: {chunk_text}\n"
        f"Category:"
    )

    inputs = tokenizer(
        prompt,
        return_tensors="pt",
        padding=True,
        truncation=True,
        max_length=256
    ).to(device)

    with torch.no_grad():
        output = model.generate(
            **inputs,
            max_length=10,
            num_beams=1,
            return_dict_in_generate=True,
            output_scores=True
        )

    decoded = tokenizer.decode(output.sequences[0], skip_special_tokens=True)
    label = normalize_label(decoded)

    # Confidence calculation
    scores = output.scores
    gen_tokens = output.sequences[:, 1:]
    logps = []

    for step, logits in enumerate(scores):
        if step < gen_tokens.shape[1]:
            tok = gen_tokens[0, step]
            logp = torch.log_softmax(logits[0], dim=-1)[tok].item()
            logps.append(logp)
    confidence = float(np.exp(np.mean(logps))) if logps else 0.5
    return label, confidence

# Classify notes
def classify_note(
    cleaned_text,
    window_size=60,
    stride=30,
    confidence_threshold=0.7,
    debug=False
):
    """
    Priority: social support > social isolation > no social reference
    """
    words = cleaned_text.split()

    # Track predictions and confidences
    chunk_predictions = []
    chunk_confidences = []

    if debug:
        print(f"Processing {len(words)} words")
    
    # Sliding window inference
    for i in range(0, len(words), stride):
        chunk = " ".join(words[i:i + window_size])
        if len(chunk.split()) < 30:
            continue

        label, confidence = predict_chunk(chunk)
        chunk_predictions.append(label)
        chunk_confidences.append(confidence)
        
        if debug:
            print(f"Chunk {len(chunk_predictions)}: {label} (conf: {confidence:.3f})")
    
    if not chunk_predictions:
        return "unknown", 0.0, {}

    # Aggregation by label
    label_scores = defaultdict(float)
    label_confidences = defaultdict(list)

    for pred, conf in zip(chunk_predictions, chunk_confidences):
        label_scores[pred] += conf
        label_confidences[pred].append(conf)

    # Calculate max confidence per label
    max_confidences = {}
    for label, confs in label_confidences.items():
        max_confidences[label] = np.max(confs) if confs else 0.0
    
    # Priority: social support > social isolation > no social reference
    final_label = "unknown"
    final_confidence = 0.0
    
    # Check in priority order
    priority_labels = ['social support', 'social isolation', 'no social reference']
    
    for priority_label in priority_labels:
        if priority_label in label_scores:
            # Use the maximum confidence for the label across chunks
            label_conf = max_confidences[priority_label]
            
            # Apply threshold
            if label_conf >= confidence_threshold:
                final_label = priority_label
                final_confidence = label_conf
                break
    
    # If no label met the threshold or if no priority labels were found, use the highest scoring
    if final_label == "unknown" and label_scores:
        # Fall back to highest scoring label
        final_label = max(label_scores.items(), key=lambda x: x[1])[0]
        final_confidence = max_confidences.get(final_label, 0.0)
        
        # Check if even the highest scoring label meets threshold
        if final_confidence < confidence_threshold:
            final_label = "unknown"
            final_confidence = 0.0

    if debug:
        print(f"Aggregation:")
        for label in ['social isolation', 'social support', 'no social reference', 'unknown']:
            if label in label_scores:
                score = label_scores[label]
                max_conf = max_confidences.get(label, 0.0)
                print(f"  {label}: score={score:.3f}, max_conf={max_conf:.3f}")
        print(f"Final: {final_label} (confidence: {final_confidence:.3f})")
    return final_label, final_confidence, dict(max_confidences)
    

# Classify full notes
def classify_full_note(
    cleaned_text,
    debug=False
):
    """
    Classify the entire note at once (for short notes < 400 words)
    """
    if len(cleaned_text.split()) < 50:
        prompt = (
            f"Classify the text into exactly one category: "
            f"['social isolation', 'no social reference', or 'social support'].\n"
            f"Text: {cleaned_text}\n"
            f"Category:"
        )
    else:
        words = cleaned_text.split()[:400]
        prompt = (
            f"Classify the text into exactly one category: "
            f"['social isolation', 'no social reference', or 'social support'].\n"
            f"Text: {' '.join(words)}\n"
            f"Category:"
        )

    inputs = tokenizer(
        prompt,
        return_tensors="pt",
        padding=True,
        truncation=True,
        max_length=512
    ).to(device)

    with torch.no_grad():
        output = model.generate(
            **inputs,
            max_length=10,
            num_beams=2,
            return_dict_in_generate=True,
            output_scores=True
        )
    decoded = tokenizer.decode(output.sequences[0], skip_special_tokens=True)
    label = normalize_label(decoded)

    # Confidence calculation
    scores = output.scores
    gen_tokens = output.sequences[:, 1:]
    logps = []
    for step, logits in enumerate(scores):
        if step < gen_tokens.shape[1]:
            tok = gen_tokens[0, step]
            logp = torch.log_softmax(logits[0], dim=-1)[tok].item()
            logps.append(logp)
    confidence = float(np.exp(np.max(logps))) if logps else 0.5
    
    if debug:
        print(f"Full note classification: {label} (confidence: {confidence:.3f})")
    return label, confidence

# Smart classifier
def smart_classify_note(
    original_text,
    debug=False
):
    """
    Smart classifier - Threshold-based approach
    """
    cleaned_text = clean_text(original_text)
    word_count = len(cleaned_text.split())

    # Skip blank text
    if not cleaned_text or word_count < 5:
        return None, 0.0, cleaned_text

    if debug:
        print(f"Note stats: {word_count} words")

    # Chunking for longer notes
    CHUNKING_THRESHOLD = 400
    
    if word_count < CHUNKING_THRESHOLD:
        # Short notes
        if debug:
            print(f"Using full-note classification ({word_count} < {CHUNKING_THRESHOLD})")
        label, conf = classify_full_note(cleaned_text, debug=debug)
    else:
        # Longer notes: use chunking
        if debug:
            print(f"Using chunking approach ({word_count} >= {CHUNKING_THRESHOLD})")
        label, conf, _ = classify_note(cleaned_text, debug=debug)
    
    return label, conf, cleaned_text

# Initialize csv
def initialize_csv():
    if not os.path.exists(output_csv):
        df = pd.DataFrame(columns=[
            'file_name', 'cleaned_text', 'prediction', 
            'confidence', 'cleaned_length', 'word_count'
        ])
        df.to_csv(output_csv, index=False)
        print(f"Created new CSV: {output_csv}")
    else:
        print(f"Appending to existing CSV: {output_csv}")

# Append result to csv
def append_to_csv(result):
    df = pd.DataFrame([result])
    df.to_csv(output_csv, mode='a', header=False, index=False)
    print(f"Saved result for {result['file_name']} to CSV")

# Process all files
def process_notes(input_dir, processed_dir):
    os.makedirs(processed_dir, exist_ok=True)
    text_files = glob.glob(os.path.join(input_dir, "*.txt"))
    
    # Initialize csv
    initialize_csv()
    
    stats = defaultdict(int)
    processed_files = set()

    # Load already processed files from csv
    if os.path.exists(output_csv):
        existing_df = pd.read_csv(output_csv)
        processed_files = set(existing_df['file_name'].tolist())
        print(f"Found {len(processed_files)} already processed files")

    for file_path in text_files:
        file_name = os.path.basename(file_path)
        
        # Skip if a file is already processed
        if file_name in processed_files:
            print(f"Skipping already processed: {file_name}")
            continue

        try:
            with open(file_path, 'r', encoding='utf-8', errors='ignore') as f:
                original_text = f.read().strip()

            if not original_text:
                continue

            print(f"\nProcessing: {file_name}")
            print(f"Original text length: {len(original_text)} chars, {len(original_text.split())} words")
            
            # Get prediction
            prediction, confidence, cleaned_text = smart_classify_note(original_text, debug=True)

            # Create result
            result = {
                'file_name': file_name,
                'cleaned_text': cleaned_text,
                'prediction': prediction,
                'confidence': confidence,
                'cleaned_length': len(cleaned_text),
                'word_count': len(cleaned_text.split())
            }

            # Append to csv
            append_to_csv(result)

            stats[prediction] += 1
            print(f"Final: {file_name} → {prediction} (confidence: {confidence:.3f})")

            # Move to processed folder
            shutil.move(file_path, os.path.join(processed_dir, file_name))

        except Exception as e:
            print(f"Error with {file_name}: {e}")
            continue

    # Final statistics
    print(f"\n")
    print("FINAL STATISTICS:")
    total_processed = len(text_files)
    
    print(f"Total files processed: {total_processed}")

    for label in ['social isolation', 'social support', 'no social reference', 'unknown']:
        count = stats.get(label, 0)
        percentage = (count / total_processed) * 100 if total_processed else 0
        print(f"  {label}: {count} ({percentage:.1f}%)")

    return total_processed

